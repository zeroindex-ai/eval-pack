import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Result } from '../core/schema.js';
import type { RunReport } from '../core/runner.js';
import { STYLES } from './styles.js';
import { escape, renderCategoryTable, renderFailureCard, renderPassRow } from './template.js';

/**
 * Resolve the installed eval-pack version for the report footer (PROJECT.md
 * §6). Read at runtime from the package's own package.json — compiled to
 * `dist/report-html/index.js`, so package.json sits two directories up.
 * Falls back to `'unknown'` if it can't be read, so rendering never throws.
 */
function readPackageVersion(): string {
  try {
    const pkgUrl = new URL('../../package.json', import.meta.url);
    const pkg = JSON.parse(readFileSync(fileURLToPath(pkgUrl), 'utf8')) as { version?: string };
    return pkg.version ?? 'unknown';
  } catch {
    return 'unknown';
  }
}

// Memoized lazily so importing this module is side-effect-free: the version is
// read from disk on the first renderHtml call rather than at module load.
let cachedVersion: string | undefined;
function getPackageVersion(): string {
  if (cachedVersion === undefined) cachedVersion = readPackageVersion();
  return cachedVersion;
}

export type RenderOptions = {
  /** Project name shown in the report title. Default: "Eval results". */
  projectName?: string;
  /** Pass-rate threshold to display alongside the headline number. */
  threshold?: number;
  /** Override the full title. Takes precedence over projectName. */
  title?: string;
  /** Hook to redact a result before rendering. Stubbed in v0.1 — call site
   *  is wired so consumers can plug in once they need it. */
  redact?: (result: Result) => Result;
};

/**
 * Render a RunReport as a single self-contained HTML string. No external
 * assets, no client JS — safe to view via file:// or embed via iframe.
 */
export function renderHtml(report: RunReport, opts: RenderOptions = {}): string {
  const projectName = opts.projectName ?? 'Eval results';
  const title = opts.title ?? `${projectName} eval results`;
  const results = opts.redact ? report.results.map(opts.redact) : report.results;
  const total = results.length;
  const passed = results.filter((r) => r.pass).length;
  const passRate = total > 0 ? passed / total : 0;
  const passPct = (passRate * 100).toFixed(1);
  const meetsThreshold = opts.threshold === undefined ? true : passRate >= opts.threshold;
  const thresholdLabel =
    opts.threshold !== undefined ? `<small>/ threshold ${(opts.threshold * 100).toFixed(0)}%</small>` : '';
  const failures = results.filter((r) => !r.pass);
  const passing = results.filter((r) => r.pass);

  const failuresSection =
    failures.length > 0
      ? `
        <h2>Failures (${failures.length})</h2>
        ${failures.map(renderFailureCard).join('\n')}`
      : '';

  const passingSection =
    passing.length > 0
      ? `
        <h2>Passing (${passing.length})</h2>
        <details>
          <summary class="pass">Show ${passing.length} passing items</summary>
          <div class="body">
            <table>
              <thead><tr><th>ID</th><th>Category</th><th>Question</th><th>Total ms</th></tr></thead>
              <tbody>${passing.map(renderPassRow).join('\n')}</tbody>
            </table>
          </div>
        </details>`
      : '';

  const errorsSection =
    report.errors.length > 0
      ? `
        <h2>Errors (${report.errors.length})</h2>
        <table>
          <thead><tr><th>Item</th><th>Error</th></tr></thead>
          <tbody>
            ${report.errors
              .map(
                (e) =>
                  `<tr><td><code>${escape(e.id)}</code></td><td><code>${escape(e.error)}</code></td></tr>`
              )
              .join('\n')}
          </tbody>
        </table>`
      : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${escape(title)}</title>
  <style>${STYLES}</style>
</head>
<body>
  <header>
    <h1>${escape(title)}</h1>
    <div class="meta">
      <span>Generated: <code>${escape(report.ran)}</code></span>
      <span>Judge: <code>${escape(report.judgeName ?? 'none')}</code></span>
      <span>Items: ${total}</span>
      <span>Errored: ${report.errors.length}</span>
    </div>
    <div class="pass-rate ${meetsThreshold ? 'ok' : 'bad'}">${passPct}% ${thresholdLabel}</div>
  </header>

  <h2>By category</h2>
  ${renderCategoryTable(results)}
  ${failuresSection}
  ${passingSection}
  ${errorsSection}

  <footer>
    Generated by <a href="https://github.com/zeroindex-ai/eval-pack">@zeroindex-ai/eval-pack</a> v${escape(getPackageVersion())}
  </footer>
</body>
</html>`;
}
